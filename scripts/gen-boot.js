// Builds the boot sequence cartridge (boot/boot.vly) and writes it where the hosts that run it can use it:
//   src/boot/boot-rom.js   for the browser players and exported games (BOOT_ROM, BOOT_FRAMES)
//   c/boot_rom.h           for the native player and the firmware (vly_boot_rom, VLY_BOOT_FRAMES)
// A host runs this cartridge for BOOT_FRAMES, then starts the game on a fresh machine. The game never sees it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildFile } from '../src/tools/build.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BOOT_FRAMES = 130;
const b = await buildFile(path.join(root, 'boot', 'boot.vly'));
const rom = Buffer.from(b.bytes);
fs.mkdirSync(path.join(root, 'src', 'boot'), { recursive: true });
fs.writeFileSync(path.join(root, 'src', 'boot', 'boot-rom.js'),
  `// Generated by scripts/gen-boot.js from boot/boot.vly. Do not edit.\nexport const BOOT_FRAMES = ${BOOT_FRAMES};\nexport const BOOT_ROM = Uint8Array.from(atob('${rom.toString('base64')}'), (c) => c.charCodeAt(0));\n`);
const rows = [];
for (let i = 0; i < rom.length; i += 16) rows.push('  ' + Array.from(rom.subarray(i, i + 16), (x) => '0x' + x.toString(16).padStart(2, '0')).join(', ') + ',');
fs.writeFileSync(path.join(root, 'c', 'boot_rom.h'),
  `/* Generated by scripts/gen-boot.js from boot/boot.vly. Do not edit. The boot sequence cartridge: run it for VLY_BOOT_FRAMES, then start the game. */\n#ifndef VLY_BOOT_ROM_H\n#define VLY_BOOT_ROM_H\n#define VLY_BOOT_FRAMES ${BOOT_FRAMES}\nstatic const unsigned char vly_boot_rom[${rom.length}] = {\n${rows.join('\n')}\n};\n#endif\n`);
console.log(`boot sequence: ${rom.length} bytes, ${BOOT_FRAMES} frames`);
