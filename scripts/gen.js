// Generates derived artifacts from the single sources of truth:
//   spec/isa.json      from src/core/isa.js
//   spec/font.json     from src/core/font.js (plus sha256 of the font bytes)
//   spec/font.md       a contact sheet of the font
//   c/isa_table.h      C table of opcodes, forms, lengths and costs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { OPS, formHasImm } from '../src/core/isa.js';
import { GLYPHS, FONT } from '../src/core/font.js';
import { sha256Hex } from '../src/core/sha256.js';
import * as C from '../src/core/constants.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const w = (rel, text) => { fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true }); fs.writeFileSync(path.join(root, rel), text); };

w('spec/isa.json', JSON.stringify({ specVersion: C.SPEC_VERSION, ops: OPS.map((o) => ({ ...o, length: formHasImm(o.form) ? 4 : 2 })) }, null, 2) + '\n');

const chars = Array.from({ length: 95 }, (_, i) => String.fromCharCode(0x20 + i));
const glyphs = Object.fromEntries(chars.map((ch) => [ch, GLYPHS[ch].split('/')]));
w('spec/font.json', JSON.stringify({ description: 'VLY-1 font: ASCII 0x20-0x7E, rows top to bottom, 5 pixels each drawn at tile columns 1-5, ink = color 3', sha256: sha256Hex(FONT), glyphs }, null, 2) + '\n');

let md = '# VLY-1 font\n\nGenerated from `src/core/font.js`. 95 glyphs, ASCII 0x20-0x7E. `#` is ink (color 3), `.` is background (color 0).\n' +
  `Font bytes SHA-256: \`${sha256Hex(FONT)}\`\n\n`;
for (let i = 0; i < chars.length; i += 8) {
  const group = chars.slice(i, i + 8);
  md += '```\n';
  md += group.map((c) => (`0x${c.charCodeAt(0).toString(16).toUpperCase()} ${JSON.stringify(c)}`).padEnd(11)).join(' ').trimEnd() + '\n';
  for (let r = 0; r < 8; r++) md += group.map((c) => GLYPHS[c].split('/')[r].replace(/1/g, '#').replace(/0/g, '.').padEnd(11)).join(' ').trimEnd() + '\n';
  md += '```\n\n';
}
w('spec/font.md', md);

let h = '/* Generated by scripts/gen.js from src/core/isa.js. Do not edit. */\n#ifndef VLY_ISA_TABLE_H\n#define VLY_ISA_TABLE_H\n\n';
h += '/* op, length in bytes (2 or 4), base cycles, name */\n#define VLY_OPS(X) \\\n' + OPS.map((o) => `  X(0x${o.op.toString(16).padStart(2, '0')}, ${formHasImm(o.form) ? 4 : 2}, ${o.cycles}, ${o.name})`).join(' \\\n') + '\n\n#endif\n';
w('c/isa_table.h', h);
// C font table
{
  let c = '/* Generated by scripts/gen.js from src/core/font.js. Do not edit. */\n#include <stdint.h>\nstatic const uint8_t VLY_FONT[1520] = {\n';
  for (let i = 0; i < FONT.length; i += 16) c += '  ' + Array.from(FONT.slice(i, i + 16), (b) => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',\n';
  c += '};\n';
  w('c/font_data.h', c);
}
console.log('generated spec/isa.json, spec/font.json, spec/font.md, c/isa_table.h');
