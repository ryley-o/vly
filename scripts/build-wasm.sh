#!/bin/sh
# Builds the VLY-1 core as a freestanding WebAssembly module (no libc, no imports, about 25 KB).
# Needs clang with the wasm32 target and wasm-ld. Output: src/wasm/vly.wasm and src/wasm/wasm-data.js (base64).
set -e
cd "$(dirname "$0")/.."
mkdir -p src/wasm c/build
CFLAGS="--target=wasm32 -O2 -ffreestanding -nostdlib -DVLY_NO_LIBC -Wall -Wextra"
clang $CFLAGS -fno-builtin -c c/libc_min.c -o c/build/libc_min.o
clang $CFLAGS -c c/vly.c -o c/build/vly_w.o
clang $CFLAGS -c c/wasm_api.c -o c/build/wasm_api.o
wasm-ld --no-entry --strip-all -z stack-size=131072 --initial-memory=2097152 --max-memory=2097152 \
  c/build/libc_min.o c/build/vly_w.o c/build/wasm_api.o -o src/wasm/vly.wasm
node -e "
const fs=require('fs');
const b=fs.readFileSync('src/wasm/vly.wasm');
fs.writeFileSync('src/wasm/wasm-data.js','// Generated by scripts/build-wasm.sh. Base64 of src/wasm/vly.wasm.\nexport const WASM_BASE64 = \''+b.toString('base64')+'\';\n');
console.log('wrote src/wasm/vly.wasm ('+b.length+' bytes) and wasm-data.js');
"
