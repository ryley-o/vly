// Originality: is this game its own, or a template or sample game with a new skin?
// A game is a set of significant source lines (code, tables) and blocks (one tile or sprite of art, one whole level map). We compare them with
// the same things from every shipped template and sample game. Lines that appear in three or more of those (the boilerplate every game shares,
// `load_font(0);` and friends) count for nothing in either direction. The index is src/tools/originality-index.json (npm run gen rebuilds it).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const INDEX_FILE = path.join(here, 'originality-index.json');
const COMMON_IN = 3;                       // a line or block found in this many reference games is boilerplate

const fnv = (s) => { let h = 0x811c9dc5; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; } return h.toString(36); };

/** Significant lines of a .vly source: comments and whitespace removed, short and trivial lines dropped. */
export function sourceLines(text) {
  const out = new Set();
  for (const raw of String(text).split(/\r?\n/)) {
    const line = raw.replace(/\/\/.*$/, '').replace(/\s+/g, ' ').trim();
    if (line.length < 16 || /^[{}();,\s]*$/.test(line)) continue;
    out.add(fnv(line));
  }
  return out;
}

/** Blocks of art and levels: each tile or sprite of a .tiles file (pixels only, the name does not count), and each whole .map file. */
export function artBlocks(name, text) {
  const out = new Set();
  const t = String(text).replace(/\r\n/g, '\n');
  if (/\.map$/i.test(name)) {
    const rows = t.split('\n').map((r) => r.trimEnd()).filter((r) => r.trim());
    if (rows.length >= 3) out.add(fnv(rows.join('\n')));
  } else if (/\.tiles$/i.test(name)) {
    let rows = [];
    const flush = () => { if (rows.length >= 4) out.add(fnv(rows.join('\n'))); rows = []; };
    for (const raw of t.split('\n')) {
      const l = raw.trim();
      if (/^(tile|sprite|rotate)\b/.test(l)) { flush(); continue; }
      if (/^[.0-3#]+$/.test(l) && l.length >= 4) rows.push(l); else if (l && !l.startsWith('#')) flush();
    }
    flush();
  }
  return out;
}

/** A project's fingerprint from its files: { 'src/main.vly': text, 'assets/art.tiles': text, ... }. */
export function fingerprint(files) {
  const lines = new Set(), blocks = new Set();
  for (const [name, text] of Object.entries(files)) {
    if (typeof text !== 'string') continue;
    if (/\.vly$/i.test(name)) for (const h of sourceLines(text)) lines.add(h);
    else for (const h of artBlocks(name, text)) blocks.add(h);
  }
  return { lines, blocks };
}

/** Read every source and art file of a project folder (src/ and assets/, text only). */
export function readProjectFiles(dir) {
  const files = {};
  const walk = (d, rel) => {
    if (!fs.existsSync(d)) return;
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name), r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(p, r);
      else if (/\.(vly|tiles|map)$/i.test(e.name) && fs.statSync(p).size < 400_000) files[r] = fs.readFileSync(p, 'utf8');
    }
  };
  walk(path.join(dir, 'src'), 'src'); walk(path.join(dir, 'assets'), 'assets');
  return files;
}

/** Build the index from reference projects: { name: dir }. */
export function buildIndex(refs) {
  const fps = Object.entries(refs).map(([name, dir]) => [name, fingerprint(readProjectFiles(dir))]);
  const count = (key) => { const m = new Map(); for (const [, fp] of fps) for (const h of fp[key]) m.set(h, (m.get(h) || 0) + 1); return m; };
  const lc = count('lines'), bc = count('blocks');
  const common = (m) => [...m].filter(([, n]) => n >= COMMON_IN).map(([h]) => h).sort();
  return {
    about: 'Hashes of the significant source lines and art/level blocks of every template and sample game (src/tools/originality.js). Generated by npm run gen.',
    commonLines: common(lc), commonBlocks: common(bc),
    refs: Object.fromEntries(fps.map(([name, fp]) => [name, { lines: [...fp.lines].filter((h) => lc.get(h) < COMMON_IN).sort(), blocks: [...fp.blocks].filter((h) => bc.get(h) < COMMON_IN).sort() }])),
  };
}

let cached = null;
export function loadIndex(file = INDEX_FILE) { if (!cached || cached.file !== file) cached = { file, data: JSON.parse(fs.readFileSync(file, 'utf8')) }; return cached.data; }

/**
 * How much of this project is one reference game's? Returns the references sorted by overlap:
 * code = share of the project's own (non-boilerplate) lines found in that reference; art = share of its art and level blocks.
 */
export function compare(files, index = loadIndex()) {
  const fp = fingerprint(files);
  const cl = new Set(index.commonLines), cb = new Set(index.commonBlocks);
  const own = [...fp.lines].filter((h) => !cl.has(h)), ownB = [...fp.blocks].filter((h) => !cb.has(h));
  const rows = Object.entries(index.refs).map(([name, r]) => {
    const rl = new Set(r.lines), rb = new Set(r.blocks);
    const sharedL = own.filter((h) => rl.has(h)).length, sharedB = ownB.filter((h) => rb.has(h)).length;
    return { name, code: own.length ? sharedL / own.length : 0, art: ownB.length ? sharedB / ownB.length : 0, sharedLines: sharedL, sharedBlocks: sharedB };
  }).sort((a, b) => Math.max(b.code, b.art) - Math.max(a.code, a.art));
  return { lines: own.length, blocks: ownB.length, refs: rows };
}

/** A verdict: always a 'warn' at most (a nudge for the agent, never a block): a re-skin when most of the code or the levels are a reference's, or a lot of borrowing. */
export function verdict(c) {
  const top = c.refs[0];
  if (!top) return { status: 'pass' };
  const codeFail = c.lines >= 20 && top.code >= 0.5, codeWarn = c.lines >= 20 && top.code >= 0.25;
  const artFail = c.blocks >= 6 && top.art >= 0.8, artWarn = c.blocks >= 6 && top.art >= 0.5;
  const pct = (x) => `${Math.round(100 * x)}%`;
  if (codeFail || artFail) return { status: 'warn', reskin: true, top, message: `this looks like a re-skin of ${top.name}: ${pct(top.code)} of its code lines and ${pct(top.art)} of its art and levels are the same`, hint: `Templates and sample games are for learning techniques, not for shipping. Design your own game: your own rules, levels and art, with your own code structure. Borrow an idea or a function, not the game.` };
  if (codeWarn || artWarn) return { status: 'warn', top, message: `a lot of this is borrowed from ${top.name}: ${pct(top.code)} of its code lines and ${pct(top.art)} of its art and levels are the same`, hint: 'Make the parts that define the game (rules, levels, art, the main loop) your own. Keep shared helper code only where it is truly generic.' };
  return { status: 'pass', top };
}
