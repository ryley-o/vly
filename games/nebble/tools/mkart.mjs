const out = [];
const tile = (name, rows) => { if (rows.length !== 8 || rows.some((r) => r.length !== 8)) throw new Error('bad tile ' + name + ' ' + rows.map((r) => r.length)); out.push(`tile ${name}:`); rows.forEach((r) => out.push('  ' + r)); };
const spr = (name, w, h, rows) => { if (rows.length !== h * 8 || rows.some((r) => r.length !== w * 8)) throw new Error('bad sprite ' + name + ' ' + rows.length + 'x' + rows[0].length); out.push(`sprite ${name} ${w}x${h}:`); rows.forEach((r) => out.push('  ' + r)); };
const T = (s) => s.trim().split('\n').map((r) => r.trim());

class Cv {
  constructor(w, h) { this.w = w; this.h = h; this.p = Array.from({ length: h }, () => Array(w).fill(0)); }
  px(x, y, c) { x = Math.round(x); y = Math.round(y); if (x >= 0 && y >= 0 && x < this.w && y < this.h) this.p[y][x] = c; }
  get(x, y) { return x >= 0 && y >= 0 && x < this.w && y < this.h ? this.p[y][x] : 0; }
  ell(cx, cy, rx, ry, c) { for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) { const dx = (x + 0.5 - cx) / rx, dy = (y + 0.5 - cy) / ry; if (dx * dx + dy * dy <= 1) this.p[y][x] = c; } }
  rect(x0, y0, x1, y1, c) { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) this.px(x, y, c); }
  tri(a, b, c, col) { const [x1, y1] = a, [x2, y2] = b, [x3, y3] = c; const d = (y2 - y3) * (x1 - x3) + (x3 - x2) * (y1 - y3);
    for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) { const px = x + 0.5, py = y + 0.5; const l1 = ((y2 - y3) * (px - x3) + (x3 - x2) * (py - y3)) / d; const l2 = ((y3 - y1) * (px - x3) + (x1 - x3) * (py - y3)) / d; if (l1 >= 0 && l2 >= 0 && 1 - l1 - l2 >= 0) this.p[y][x] = col; } }
  line(x0, y0, x1, y1, c) { const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0)); for (let i = 0; i <= n; i++) this.px(x0 + (x1 - x0) * i / (n || 1), y0 + (y1 - y0) * i / (n || 1), c); }
  outline(c = 3) { const q = this.p.map((r) => r.slice()); for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) if (!this.p[y][x] && (this.get(x - 1, y) || this.get(x + 1, y) || this.get(x, y - 1) || this.get(x, y + 1))) q[y][x] = c; this.p = q; }
  rot90() { const c = new Cv(this.h, this.w); for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) c.p[x][this.h - 1 - y] = this.p[y][x]; return c; }
  rows() { return this.p.map((r) => r.map((c) => (c ? String(c) : '.')).join('')); }
}

