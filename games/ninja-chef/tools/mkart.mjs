// Generates assets/big.tiles (bosses, cloud, sun) from shape code. Run: node tools/mkart.mjs
import fs from 'node:fs';
function canvas(w, h) {
  const g = Array.from({ length: h }, () => Array(w).fill('.'));
  const c = {
    px(x, y, v) { x = Math.round(x); y = Math.round(y); if (x >= 0 && y >= 0 && x < w && y < h) g[y][x] = v; },
    rect(x0, y0, x1, y1, v) { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) c.px(x, y, v); },
    ell(cx, cy, rx, ry, v) { for (let y = Math.floor(cy - ry); y <= Math.ceil(cy + ry); y++) for (let x = Math.floor(cx - rx); x <= Math.ceil(cx + rx); x++) { const dx = (x - cx) / rx, dy = (y - cy) / ry; if (dx * dx + dy * dy <= 1) c.px(x, y, v); } },
    line(x0, y0, x1, y1, v) { const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0)); for (let i = 0; i <= n; i++) c.px(x0 + (x1 - x0) * i / (n || 1), y0 + (y1 - y0) * i / (n || 1), v); },
    mirror() { for (let y = 0; y < h; y++) for (let x = 0; x < w / 2; x++) if (g[y][x] !== '.') g[y][w - 1 - x] = g[y][x]; },
    out(name, tw, th) { return `sprite ${name} ${tw}x${th}:\n` + g.map((r) => '  ' + r.join('')).join('\n') + '\n'; },
  };
  return c;
}
