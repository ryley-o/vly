// Generates the table art (assets/table.tiles + src/table_data.vly), the big 16x16 letters (assets/big.tiles) and
// the sprites (assets/objs.tiles). Run: node tools/mkart.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const font = JSON.parse(fs.readFileSync(path.join(here, '../../../spec/font.json'), 'utf8')).glyphs;

// ---------------- the table (160 x 144 canvas) ----------------
const W = 160, H = 144;
const IL = 8, IR = 152, IT = 16, IB = 136;      // interior of the table in pixels
const GY0 = 48, GY1 = 104;                        // goal mouth
const px = Array.from({ length: H }, () => new Array(W).fill(0));
const pal = Array.from({ length: 18 }, () => new Array(20).fill(0));
const RAIL = [0, 1, 2, 2, 3, 3, 2, 0];           // by depth from the table edge (0 = lip next to the table)
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
  const inside = x >= IL && x < IR && y >= IT && y < IB;
  if (y < 8) continue;                            // HUD row: blank
  if (inside) {
    let c = 0;
    if ((x & 7) === 3 && (y & 7) === 3) c = 1;    // air holes
    const dc = Math.hypot(x + 0.5 - 80, y + 0.5 - 76);
    const dl = Math.hypot(x + 0.5 - IL, y + 0.5 - 76), dr = Math.hypot(x + 0.5 - IR, y + 0.5 - 76);
    if (Math.abs(dc - 16) < 0.75) c = 2;
    if (dc < 3) c = 2;
    if (Math.abs(dl - 27) < 0.75 && x >= IL) c = 2;
    if (Math.abs(dr - 27) < 0.75 && x < IR) c = 2;
    if (x === 79 || x === 80) c = 3;
    px[y][x] = c;
  } else {
    const dx = x < IL ? IL - 1 - x : x >= IR ? x - IR : 0;
    const dy = y < IT ? IT - 1 - y : y >= IB ? y - IB : 0;
    let c = RAIL[Math.min(7, Math.max(dx, dy))];
    if ((x < IL || x >= IR) && y >= GY0 && y < GY1) {   // the net
      const xx = x < IL ? x : 159 - x;
      c = ((xx + y) % 4 === 0 || (xx - y + 64) % 4 === 0) ? 1 : 0;
      if (xx === 0) c = 3;
    }
    px[y][x] = c;
  }
}
// palettes per cell: 0 table, 1 rails, 2 HUD, 6 net / red goal rails
for (let r = 0; r < 18; r++) for (let c = 0; c < 20; c++) {
  let p = 0;
  if (r === 0) p = 2;
  else if (r === 1 || r === 17 || c === 0 || c === 19) {
    p = 1;
    if ((c === 0 || c === 19) && r >= 5 && r <= 13) p = 6;     // rows 5-13 of the side rails: red caps at 5 and 13, net 6..12
  }
  pal[r][c] = p;
}
const uniq = new Map(); const tiles = []; const cells = [];
for (let r = 0; r < 18; r++) {
  for (let c = 0; c < 20; c++) {
    if (r === 0) { cells.push(0 | (2 << 12)); continue; }
    let s = '';
    for (let y = 0; y < 8; y++) { for (let x = 0; x < 8; x++) s += px[r * 8 + y][c * 8 + x]; s += '\n'; }
    const key = pal[r][c] + ':' + s;
    if (!uniq.has(key)) { uniq.set(key, tiles.length); tiles.push(s); }
    cells.push((100 + uniq.get(key)) | (pal[r][c] << 12));
  }
}
let out = '# generated by tools/mkart.mjs: the air hockey table\n';
tiles.forEach((s, i) => { out += `tile t${i}:\n` + s.split('\n').filter(Boolean).map((l) => '  ' + l.replace(/0/g, '.')).join('\n') + '\n'; });
fs.writeFileSync(path.join(root, 'assets/table.tiles'), out);
let v = '// generated by tools/mkart.mjs: 20 x 18 cells of the table, tile (100 + n) | palette << 12\ntable table_cells = {\n';
for (let r = 0; r < 18; r++) v += '  ' + cells.slice(r * 20, r * 20 + 20).join(', ') + (r < 17 ? ',' : '') + '\n';
v += '};\nconst TABLE_TILES = ' + tiles.length + ';\n';
fs.writeFileSync(path.join(root, 'src/table_data.vly'), v);
console.log('table tiles', tiles.length);

// ---------------- big letters: 2x2 sprites scaled from the font, with an outline ----------------
const chars = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ!';
let big = '# generated by tools/mkart.mjs: big letters (font x2 with an outline); colour 3 = ink, 1 = outline\n';
for (const ch of chars) {
  const g = font[ch];
  const grid = Array.from({ length: 16 }, () => new Array(16).fill(0));
  for (let r = 0; r < 8; r++) for (let c = 0; c < 8; c++) {
    // glyph columns: 5 px drawn at tile columns 1-5
    const on = g[r] && c >= 1 && c <= 5 && g[r][c - 1] === '1';
    if (on) for (let a = 0; a < 2; a++) for (let b = 0; b < 2; b++) grid[1 + r * 2 + a][2 + (c - 1) * 2 + b + 3 - 0] = 3;
  }
  const o = grid.map((row) => row.slice());
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) if (grid[y][x] === 0) {
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) { const yy = y + dy, xx = x + dx; if (yy >= 0 && yy < 16 && xx >= 0 && xx < 16 && grid[yy][xx] === 3) o[y][x] = 1; }
  }
  const name = ch === '!' ? 'bang' : ch;
  big += `sprite big${name} 2x2:\n` + o.map((row) => '  ' + row.join('').replace(/0/g, '.')).join('\n') + '\n';
}
fs.writeFileSync(path.join(root, 'assets/big.tiles'), big);

// ---------------- sprites: mallet 16x16, puck 8x8, confetti ----------------
function disc(n, f) { const g = []; for (let y = 0; y < n; y++) { let row = ''; for (let x = 0; x < n; x++) row += f(x + 0.5 - n / 2, y + 0.5 - n / 2, x, y); g.push('  ' + row); } return g.join('\n'); }
const mallet = disc(16, (dx, dy, x, y) => {
  const d = Math.hypot(dx, dy);
  if (d > 7.6) return '.';
  if (d > 6.2) return '3';
  if (d > 4.3) return (dx + dy < -2.2) ? '1' : '2';
  if (d > 3.2) return '3';
  if (Math.hypot(dx + 1.2, dy + 1.2) < 1.6) return '1';
  return '2';
});
const puck = disc(8, (dx, dy) => {
  const d = Math.hypot(dx, dy);
  if (d > 3.9) return '.';
  if (d > 2.9) return '3';
  if (dx + dy < -1.8) return '1';
  return '2';
});
const conf = '  ........\n  ........\n  ..333...\n  ..333...\n  ..333...\n  ........\n  ........\n  ........';
const spark = '  ........\n  ...3....\n  ...3....\n  .33333..\n  ...3....\n  ...3....\n  ........\n  ........';
const arrow = '  ........\n  ..3.....\n  ..33....\n  ..333...\n  ..33....\n  ..3.....\n  ........\n  ........';
fs.writeFileSync(path.join(root, 'assets/objs.tiles'),
  `# generated by tools/mkart.mjs\nsprite mallet 2x2:\n${mallet}\ntile puck:\n${puck}\ntile conf:\n${conf}\ntile spark:\n${spark}\ntile arrow:\n${arrow}\n`);
console.log('ok');
