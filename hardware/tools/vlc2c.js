#!/usr/bin/env node
// Turns a cartridge into a C header: node vlc2c.js game.vlc > cart.h
// The array is `static const`, so on a microcontroller it stays in flash and the emulator reads it in place.
import fs from 'node:fs';

const file = process.argv[2];
if (!file) { console.error('usage: vlc2c.js <cart.vlc>'); process.exit(2); }
const rom = fs.readFileSync(file);
if (rom.length < 16 || rom[0] !== 0x56 || rom[1] !== 0x43) { console.error(`${file}: not a VLY-1 cartridge`); process.exit(1); }
const lines = [];
for (let i = 0; i < rom.length; i += 16) lines.push('  ' + Array.from(rom.subarray(i, i + 16), (b) => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
process.stdout.write(`/* Generated by vlc2c.js from ${file.split('/').pop()}: ${rom.length} bytes. */
#include <stdint.h>
static const uint8_t cart_data[${rom.length}] __attribute__((aligned(4))) = {
${lines.join('\n')}
};
static const uint32_t cart_size = ${rom.length};
`);
